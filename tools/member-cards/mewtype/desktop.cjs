module.exports = async function arrangeDesktop({shelfURL, maruArtwork}) {
  const sheet = document.querySelector('main.foldsheet[data-band-id="3"]');
  if (!sheet) return;
  const strip = document.createElement('div');
  strip.className = 'desktop-bar';
  strip.setAttribute('aria-hidden','true');
  sheet.before(strip);
  const panel = sheet.querySelector('.lyric-page .filter-panel');
  const header = sheet.querySelector('.lyric-page header');
  const studio = document.createElement('div');
  studio.className = 'studio-desk';
  header.before(studio);
  studio.append(header,panel);
  const shelf = sheet.querySelector('.band-shelf');
  shelf.src = shelfURL + new URL(shelf.src).hash;
  await shelf.decode();
  const animals = document.createElement('img');
  animals.className = 'animal-orbit';
  animals.src = new URL('animal-orbit.svg', shelfURL).href;
  animals.alt = '黄耳廓狐、倒悬的粉兔、仰躺的蓝熊、抱住白球的紫犬和戴耳机的雪貂';
  const relations = sheet.querySelector('.relation-page');
  if (relations) sheet.append(animals);
  else studio.after(animals);
  const portrait = sheet.querySelector('.host-corner .maru');
  const oldCorner = portrait.parentElement;
  const art = new DOMParser().parseFromString(maruArtwork,'image/svg+xml').documentElement;
  art.setAttribute('viewBox','-4 5 212 151');
  art.querySelectorAll('[fill="url(#bar-paper)"], [stroke="url(#bar-ink)"]').forEach(el => el.remove());
  portrait.src = 'data:image/svg+xml;charset=utf-8,' + encodeURIComponent(new XMLSerializer().serializeToString(art));
  portrait.alt = '丸君的前爪搭在中栏窗口右上角的外框上';
  portrait.className = 'window-maru';
  studio.append(portrait);
  oldCorner.remove();
  await Promise.all([animals.decode(),portrait.decode()]);
};
